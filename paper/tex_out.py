"""Write paper/numbers.tex (macros) and paper/tables/*.tex from the numbers computed by make_figures.py."""
import os

from leblanc import report
from leblanc.config import STUDY

BS = "\\"
ROW_END = " " + BS + BS


def tex(s):
    return (str(s).replace(BS, BS + "textbackslash{}").replace("%", BS + "%").replace("&", BS + "&")
            .replace("_", BS + "_").replace("#", BS + "#").replace("$", BS + "$"))


def f1(x):
    return "--" if x is None else f"{x:.1f}"


def ci(d):
    return "--" if d["rate"] is None else f"{d['rate']:.1f} [{d['lo']:.1f}, {d['hi']:.1f}]"


def thousands(n):
    return f"{n:,}".replace(",", "{,}")


def table(fh, colspec, header, lines):
    fh.write(BS + "begin{tabular}{" + colspec + "}\n" + BS + "toprule\n")
    fh.write(" & ".join(header) + ROW_END + "\n" + BS + "midrule\n")
    fh.write("\n".join(lines) + "\n" + BS + "bottomrule\n" + BS + "end{tabular}\n")


def write_all(N, MODELS, LAB, HERE):
    TAB = os.path.join(HERE, "tables")
    os.makedirs(TAB, exist_ok=True)
    macros = {
        "NTasks": N["tasks"], "NCwe": N["cwe_types"], "NSpValid": N["sp_valid_tasks"], "Reps": STUDY["reps"],
        "Temp": STUDY["temperature"], "Effort": STUDY["reasoning_effort"], "MaxTok": thousands(STUDY["max_tokens"]),
        "MaxRounds": STUDY["scan_repair_max_rounds"], "GenericLine": tex(STUDY["generic_line"]),
        "NCells": thousands(N["cells_done"]), "NCalls": thousands(N["calls"]["ok"] or 0),
        "TotalCost": f"{N['calls']['cost_usd']:.2f}", "RunMinutes": f"{N['calls']['minutes']:.0f}",
        "Kappa": "--" if N["scanner_vs_test"]["kappa"] is None else f"{N['scanner_vs_test']['kappa']:.3f}",
    }
    with open(os.path.join(HERE, "numbers.tex"), "w", encoding="utf-8") as fh:
        fh.write("% generated by paper/make_figures.py from the run database; do not edit\n")
        for k, v in macros.items():
            fh.write(BS + "newcommand{" + BS + k + "}{" + str(v) + "}\n")

    rows = []
    for m in MODELS:
        d = N["rq1"][LAB[m]]
        rows.append(" & ".join([LAB[m], str(d["vuln_task"]["n"]), ci(d["vuln_task"]), ci(d["sp_fail"]), ci(d["fp_pass"]),
                                ci(d["secure_pass"]), f1(d["sp_fail_strict"]["rate"])]) + ROW_END)
    with open(os.path.join(TAB, "rq1.tex"), "w", encoding="utf-8") as fh:
        table(fh, "lrlllll", ["Model", "$n$", "Flagged (static)", "Sec.\\ test fails", "Works", "Secure and works",
                              "Sec.\\ fails (strict)"], rows)

    def contrast(rows_, metrics, fname, label):
        lines = []
        for r in rows_:
            if r["metric"] not in metrics:
                continue
            q = "--" if r["q"] is None else ("$<$0.001" if r["q"] < 0.001 else f"{r['q']:.3f}")
            eff = "--" if r["effect_pp"] is None else f"{r['effect_pp']:+.1f}"
            lines.append(" & ".join([r["model"], label[r["metric"]], f"{r['b']} vs {r['a']}", str(r["n"]), f1(r["rate_a"]),
                                     f1(r["rate_b"]), eff, f"[{f1(r['lo'])}, {f1(r['hi'])}]", f"{r['b_only']}/{r['a_only']}",
                                     q, BS + "textit{" + r["verdict"] + "}"]) + ROW_END)
        with open(os.path.join(TAB, fname), "w", encoding="utf-8") as fh:
            table(fh, "lllrrrrlrrl", ["Model", "Metric", "Contrast", "Pairs", "A (\\%)", "B (\\%)", "$\\Delta$ (pp)",
                                      "95\\% CI", "Disc.\\ B/A", "$q$", "Verdict"], lines)

    contrast(N["rq2"], ("sp_fail", "vuln_task"), "rq2.tex", {"sp_fail": "sec.\\ fails", "vuln_task": "flagged"})
    contrast(N["rq3"], ("fp_pass", "secure_pass"), "rq3.tex", {"fp_pass": "works", "secure_pass": "secure+works"})

    lines = []
    for m in MODELS:
        for s in report.STRATS:
            d = N["rq4"][LAB[m]][s]
            lines.append(" & ".join([LAB[m], tex(s), str(d["secure_pass"]["n"]), f1(d["static_clean"]["rate"]),
                                     f1(d["sp_fail"]["rate"]), f1(d["fp_pass"]["rate"]), ci(d["secure_pass"]),
                                     str(d["mean_tokens"]) if d["mean_tokens"] is not None else "--"]) + ROW_END)
    with open(os.path.join(TAB, "rq4.tex"), "w", encoding="utf-8") as fh:
        table(fh, "llrrrrlr", ["Model", "Strategy", "$n$", "Scanner clean", "Sec.\\ fails", "Works", "Secure and works",
                               "Tokens"], lines)

    lines = [" & ".join(tex(x) for x in r) + ROW_END for r in N["rq5_table"]]
    with open(os.path.join(TAB, "rq5.tex"), "w", encoding="utf-8") as fh:
        table(fh, "llrrrrrrr", ["Model", "Strategy", "$n$", "Secure+works", "Tokens", "$\\Delta$tok", "$\\Delta$",
                                "Tok/+1pp", "\\$/1k"], lines)
    print("tables:", sorted(os.listdir(TAB)))
